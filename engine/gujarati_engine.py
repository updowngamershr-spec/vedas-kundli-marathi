def to_gujarati(text: str) -> str:
    """
    Convert Hindi / Devanagari string to authentic Gujarati text.
    Uses vocabulary mapping followed by phonetic Unicode transliteration.
    """
    if not isinstance(text, str) or not text:
        return text

    res = text
    for k, v in GUJARATI_VOCAB_MAP.items():
        if k in res:
            res = res.replace(k, v)

    # Unicode Devanagari to Gujarati character shift (offset 0x0180)
    out = []
    for ch in res:
        code = ord(ch)
        # Devanagari Unicode Block: U+0900 to U+097F
        if 0x0900 <= code <= 0x097F:
            # Map nukta, danda and common punctuation correctly
            if code == 0x0964:  # Devanagari Danda '|'
                out.append('।')
            elif code == 0x0965:  # Double Danda '||'
                out.append('॥')
            else:
                gu_code = code + 0x0180
                # Check valid Gujarati Unicode Range (U+0A80 to U+0AFF)
                if 0x0A81 <= gu_code <= 0x0AFF:
                    out.append(chr(gu_code))
                else:
                    out.append(ch)
        else:
            out.append(ch)

    return "".join(out)


