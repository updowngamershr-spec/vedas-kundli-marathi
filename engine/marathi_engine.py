def to_marathi(text: str) -> str:
    """
    Transforms Hindi astrological text into authentic, natural Marathi.
    Applies grammatical phrases first, then vocabulary replacements.
    """
    if not text:
        return ""
    s = str(text)

    # 1. Apply multi-word grammatical and sentence transformations
    for k, v in MARATHI_PHRASES:
        if k in s:
            s = s.replace(k, v)

    # 2. Apply core vocabulary mapping
    for k, v in MARATHI_VOCAB_MAP.items():
        if k in s:
            s = s.replace(k, v)

    # Clean double spaces
    while "  " in s:
        s = s.replace("  ", " ")

    return s.strip()

def to_marathi_with_hindi(mr_text: str, hi_text: str) -> str:
    """Formats text as Marathi primary with Hindi in brackets."""
    mr = to_marathi(mr_text) if mr_text else to_marathi(hi_text)
    hi = hi_text if hi_text else mr_text
    if mr == hi or not hi:
        return mr
    return f"{mr} ({hi})"
