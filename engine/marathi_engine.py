def to_marathi(text: str) -> str:
    """
    Transforms Hindi or English astrological text into authentic, natural Marathi.
    1. Checks exact title dictionary.
    2. Applies multi-word phrase replacements (longest first).
    3. Applies word-boundary regex for single words and postpositions.
    """
    if not text:
        return ""
    s = str(text).strip()

    # Exact title match shortcut
    if s in MARATHI_TITLES_MAP:
        return MARATHI_TITLES_MAP[s]

    # 1. Multi-word phrase replacements
    for k, v in MARATHI_PHRASES:
        if k in s:
            s = s.replace(k, v)

    # 2. Single words with Devanagari boundary regex
    for w, r in MARATHI_SINGLE_WORDS:
        pat = rf'(?<!{DEVA_LETTER})' + re.escape(w) + rf'(?!{DEVA_LETTER})'
        s = re.sub(pat, r, s)

    # Clean double spaces
    while "  " in s:
        s = s.replace("  ", " ")

    return s.strip()

def to_marathi_with_hindi(mr_text: str, hi_text: str) -> str:
    """Returns pure Marathi representation."""
    mr = to_marathi(mr_text) if mr_text else to_marathi(hi_text)
    return mr
